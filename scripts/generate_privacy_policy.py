#!/usr/bin/env python3
"""Generate the displayed policy and archived evidence from one canonical document.

Run after reviewing docs/privacy-policy.md. Published version snapshots must never
be edited; change the policy's Version field before releasing changed text. Use
--check in validation to reject missing/stale output without writing anything.
"""

import argparse
from datetime import datetime
import hashlib
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
KOTLIN_PATH = Path("shared/src/commonMain/kotlin/in/drarunbabu/drsharmila/jananisync/data/privacy/PrivacyPolicyDocument.kt")


def artifacts(root=ROOT):
    raw = (root / "docs/privacy-policy.md").read_bytes()
    text = raw.decode("utf-8")
    if "\r" in text or not text.endswith("\n"):
        raise SystemExit("Policy source must be UTF-8 with LF endings and a final newline")
    if re.search(r"\[[A-Z][A-Z_]+\]", text):
        raise SystemExit("Policy source still contains incomplete operator fields")
    version = re.search(r"^\*\*Version:\*\* ([0-9]+\.[0-9]+)$", text, re.MULTILINE).group(1)
    date_text = re.search(r"^\*\*Effective date:\*\* (.+?)\s*$", text, re.MULTILINE).group(1)
    effective_date = datetime.strptime(date_text, "%d %B %Y").strftime("%Y-%m-%d")
    digest = hashlib.sha256(raw).hexdigest()
    presentation_version = 2
    acceptance = (
        f"Selecting ‘Accept and continue’ records acceptance of Privacy Policy version {version} "
        "for your account and service processing. It is not consent on behalf of any patient."
    )
    denial = (
        f"Selecting ‘Deny and stop’ records denial of Privacy Policy version {version}. "
        "Organisation and clinical access remain blocked."
    )
    manifest = {
        "policyVersion": version,
        "effectiveDate": effective_date,
        "policySha256": digest,
        "hashFormat": "SHA-256 of exact UTF-8 policy Markdown bytes, LF, including final newline",
        "presentationVersion": presentation_version,
        "acceptanceStatement": acceptance,
        "denialStatement": denial,
        "acceptButton": "Accept and continue",
        "denyButton": "Deny and stop",
    }
    if '"""' in text:
        raise SystemExit('Policy cannot contain a Kotlin triple-quote delimiter')
    kotlin_text = text.replace("$", "${'$'}")
    kotlin = (
        "// Generated by scripts/generate_privacy_policy.py; edit docs/privacy-policy.md.\n"
        "package `in`.drarunbabu.drsharmila.jananisync.data.privacy\n\n"
        "/** Exact policy bytes and decision wording archived for this release. */\n"
        "object PrivacyPolicyDocument {\n"
        f"    const val VERSION = {json.dumps(version)}\n"
        f"    const val EFFECTIVE_DATE = {json.dumps(effective_date)}\n"
        f"    const val SHA256 = {json.dumps(digest)}\n"
        f"    const val PRESENTATION_VERSION = {presentation_version}\n"
        f"    const val ACCEPTANCE_STATEMENT = {json.dumps(acceptance)}\n"
        f"    const val DENIAL_STATEMENT = {json.dumps(denial)}\n"
        '    const val ACCEPT_BUTTON = "Accept and continue"\n'
        '    const val DENY_BUTTON = "Deny and stop"\n'
        f'    const val CONTENT = """{kotlin_text}"""\n'
        "}\n"
    )
    return {
        root / KOTLIN_PATH: kotlin.encode("utf-8"),
        root / f"docs/privacy/{version}.md": raw,
        root / f"docs/privacy/{version}-presentation-{presentation_version}-manifest.json": (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8"),
    }


def rules_function(rules, name):
    """Extract the checked-in rules function, excluding comments and nested blocks."""
    rules = re.sub(r"/\*.*?\*/|//[^\n]*", "", rules, flags=re.DOTALL)
    match = re.search(r"\bfunction\s+" + re.escape(name) + r"\s*\([^)]*\)\s*\{", rules)
    if not match:
        raise SystemExit(f"Missing privacy rules function: {name}")
    depth = 1
    for index in range(match.end(), len(rules)):
        if rules[index] == "{":
            depth += 1
        elif rules[index] == "}":
            depth -= 1
            if depth == 0:
                return rules[match.end():index]
    raise SystemExit(f"Unclosed privacy rules function: {name}")


def verify_rules_pins(root, manifest):
    """Catch release skew; this is not a general Firestore security-rules audit."""
    rules = (root / "firestore.rules").read_text(encoding="utf-8")
    version = manifest["policyVersion"]
    digest = manifest["policySha256"]
    hash_body = rules_function(rules, "currentPrivacyPolicyHash")
    pinned_hash = re.fullmatch(r"\s*return\s+['\"]([a-f0-9]{64})['\"]\s*;\s*", hash_body)
    if not pinned_hash or pinned_hash.group(1) != digest:
        raise SystemExit("Stale policy hash pin in firestore.rules currentPrivacyPolicyHash()")

    current_body = rules_function(rules, "currentPrivacyPolicy")
    versions = re.findall(r"\bversion\s*==\s*['\"]([^'\"]+)['\"]", current_body)
    if versions != [version] or not re.search(r"\bhash\s*==\s*currentPrivacyPolicyHash\(\s*\)", current_body):
        raise SystemExit("Stale policy version/hash pin in firestore.rules currentPrivacyPolicy()")

    accepted_body = rules_function(rules, "acceptedCurrentPrivacyPolicy")
    accepted_versions = re.findall(r"\breceipt\.policyVersion\s*==\s*['\"]([^'\"]+)['\"]", accepted_body)
    accepted_hashes = re.findall(r"\breceipt\.policySha256\s*==\s*['\"]([^'\"]+)['\"]", accepted_body)
    if accepted_versions != [version] or accepted_hashes != [digest]:
        raise SystemExit("Stale policy version/hash pin in firestore.rules acceptedCurrentPrivacyPolicy()")


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    outputs = artifacts(root)
    manifest = next(json.loads(raw) for path, raw in outputs.items() if path.name.endswith("-manifest.json"))
    verify_rules_pins(root, manifest)
    # Reject a changed archive before updating any generated runtime content.
    for path, expected in outputs.items():
        if path.exists() and path.read_bytes() == expected:
            continue
        if args.check:
            raise SystemExit(f"Missing or stale generated policy artifact: {path.relative_to(root)}")
        if path.parent == root / "docs/privacy" and path.exists():
            raise SystemExit(
                f"Refusing to overwrite version snapshot {path.relative_to(root)}. "
                "Bump the Version field for a changed published policy."
            )
    for path, expected in outputs.items():
        if path.exists() and path.read_bytes() == expected:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(expected)
    print("Policy content, hash, archived snapshot, decision manifest, and Firestore rules pins agree.")


if __name__ == "__main__":
    main()
